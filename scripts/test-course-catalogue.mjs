import {chromium,expect} from '@playwright/test';
import {launchTestBrowser,waitForServiceWorkerControl} from '../lib/test/browser.mjs';
import fs from 'node:fs/promises';
import axe from 'axe-core';

const base=process.env.NUNYA_TEST_URL||'http://127.0.0.1:4176/';
const browser=await launchTestBrowser(chromium),results=[],errors=[];

try{
 for(const width of [360,1440]){
  const ctx=await browser.newContext({viewport:{width,height:900}}),p=await ctx.newPage();
  p.on('pageerror',error=>errors.push(error.message));
  await p.goto(base+'#/apprendre');
  await expect(p.locator('.nunya-course-card')).toHaveCount(29);
  const catalogueHeight=await p.locator('#nunya-course-catalogue').evaluate(el=>el.scrollHeight);
  const gitCard=p.locator('.nunya-course-card[href="#/apprendre/git-bases"]');
  await expect(gitCard).toHaveCount(1);
  await expect(gitCard).toHaveAttribute('data-domain','outils');
  if(width===1440)expect(catalogueHeight).toBeLessThanOrEqual(4000);
  const original=p.url();
  await p.locator('#nunya-course-level').selectOption('intermediaire');
  await p.locator('#nunya-course-search-submit').click();
  await expect(p.locator('.nunya-course-card')).toHaveCount(13);
  await p.locator('#nunya-course-technology').selectOption('css');
  await p.locator('#nunya-course-search-submit').click();
  await expect(p.locator('.nunya-course-card')).toHaveCount(1);
  await expect(p.locator('.nunya-course-card')).toContainText('CSS : interfaces robustes');
  await p.locator('#nunya-course-filter-clear').click();
  await p.locator('#nunya-course-technology').selectOption('sql');
  await p.locator('#nunya-course-search-submit').click();
  await expect(p.locator('.nunya-course-card')).toHaveCount(2);
  await expect(p.locator('.nunya-course-card[href="#/apprendre/sql-bases"]')).toContainText('SQL : des premières requêtes');
  expect(p.url()).toBe(original);
  await p.locator('#nunya-course-filter-clear').click();
  await p.locator('#nunya-course-query').fill('JS');
  await p.locator('#nunya-course-search-submit').click();
  await expect(p.locator('.nunya-course-card')).toHaveCount(7);
  await expect(p.locator('.nunya-course-card').first()).toContainText('JavaScript');
  await p.locator('#nunya-course-query').fill('');
  const journeyChoices=p.locator('.nunya-journey-choices');
  await expect(journeyChoices).toHaveCount(1);
  await expect(journeyChoices.locator('.nunya-journey-grid')).toBeHidden();
  await journeyChoices.locator('summary').click();
  await expect(journeyChoices.locator('.nunya-journey-grid')).toBeVisible();
  await journeyChoices.locator('summary').click();
  await p.locator('#nunya-course-technology').selectOption('git');
  await p.locator('#nunya-course-search-submit').click();
  await expect(p.locator('.nunya-course-card')).toHaveCount(1);
  await expect(p.locator('.nunya-course-card')).toHaveAttribute('href','#/apprendre/git-bases');
  await p.locator('#nunya-course-query').fill('Kotlin');
  await p.locator('#nunya-course-search-submit').click();
  await expect(p.locator('.nunya-course-card')).toHaveCount(0);
  await expect(p.locator('#nunya-course-roadmap')).toHaveCount(0);
  await p.locator('#nunya-course-empty-clear').click();
  await expect(p.locator('.nunya-course-card')).toHaveCount(29);
  await expect(p.locator('.curr-entry h2').filter({hasText:'Découverte du numérique'})).toHaveCount(1);
  await p.locator('#nunya-course-query').fill('mon filtre conservé');
  await p.locator('#nunya-course-level').selectOption('intermediaire');
  await p.locator('[data-curr=refresh-catalogue]').click();
  await expect(p.locator('#nunya-course-query')).toHaveValue('mon filtre conservé');
  await expect(p.locator('#nunya-course-level')).toHaveValue('intermediaire');
  await p.locator('#nunya-course-query').fill('');
  await p.evaluate(axe.source);
  const audit=await p.evaluate(()=>axe.run(document,{runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21aa']}}));
  expect(audit.violations.map(v=>({id:v.id,nodes:v.nodes.map(n=>n.target)}))).toEqual([]);
  expect(await p.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false);
  await p.screenshot({path:'docs/screenshots/course-catalogue-'+width+'.png',fullPage:true});
  await p.locator('[data-domain-toggle=donnees]').click();
  await expect(p.locator('#nunya-domain-body-donnees')).toBeVisible();
  await p.locator('.nunya-course-card[href="#/apprendre/sql-bases"]').click();
  await expect(p.locator('.curr-module')).toHaveCount(6);
  await expect(p.locator('.curr-module[open]')).toHaveCount(1);
  await expect(p.locator('.curr-module [aria-current=step]')).toHaveCount(1);
  await expect(p.locator('.curr-module [aria-current=step]')).toContainText('Prochaine leçon');
  await waitForServiceWorkerControl(p);
  await p.emulateMedia({media:'print'});
  await p.evaluate(()=>window.dispatchEvent(new Event('beforeprint')));
  await expect(p.locator('.curr-module[open]')).toHaveCount(6);
  await expect(p.locator('.curr-module .curr-outline')).toHaveCount(6);
  await expect(p.locator('.curr-module .curr-outline').nth(1)).toBeVisible();
  await p.evaluate(()=>window.dispatchEvent(new Event('afterprint')));
  await expect(p.locator('.curr-module[open]')).toHaveCount(1);
  await p.emulateMedia({media:'screen'});
  await p.evaluate(async()=>{for(const name of await caches.keys()){const cache=await caches.open(name);for(const request of await cache.keys())if(request.url.includes('/data/curriculum/index.json?release='))await cache.delete(request)}});
  await ctx.setOffline(true);
  await p.goto(base+'#/apprendre');
  await p.reload();
  await expect(p.locator('.nunya-course-card')).toHaveCount(29);
  results.push({width,catalogueHeight,courses:29,filters:true,gitInToolsOnce:true,discoveryPreserved:true,refreshKeepsTypedQuery:true,offlineCanonicalCatalogue:true,roadmapHonest:true,programTimeline:true,printShowsCollapsedModules:true,axeViolations:0});
  await ctx.close();
 }
 expect(errors).toEqual([]);
 await fs.writeFile('docs/COURSE_CATALOGUE_RESULTS.json',JSON.stringify({results,errors},null,2));
 console.log(JSON.stringify({results,errors}));
}finally{
 await browser.close();
}
